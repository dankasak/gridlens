    class PowerflowCardView(HomeAssistantView):
        """Proxies the Power Flow card's JS from the API — gated on the install's
        ApiKey.powerflow_card entitlement (see gridlens-api/app/cards.py's
        GET /cards/powerflow). The browser never talks to the API directly and
        never sees the API key; this view fetches server-to-server (using the
        key stored in the config entry) and re-serves the result at a fixed,
        stable URL so the Lovelace resource never has to change.

        Caches per config entry for a TTL so a page reload / several open tabs
        don't each trigger a fresh API round-trip. On a genuine network failure,
        prefers re-serving a previously fetched REAL card over downgrading to
        the paywall stub — an API/LXC outage should never nag a paying customer;
        it should only ever fail toward "keeps showing what they already had".
        The paywall stub (powerflow_locked.LOCKED_CARD_JS) is only served on an
        explicit 401/402/403 (a real "not entitled" answer) or when nothing has
        ever been fetched successfully for this entry.
        """

        url = "/api/grid_lens/cards/grid-lens-powerflow-card.js"
        name = "api:grid_lens:powerflow_card"
        requires_auth = False

        _TTL_ENTITLED = 300   # seconds — a real subscription rarely lapses mid-session
        _TTL_LOCKED = 60      # shorter — so upgrading is reflected reasonably promptly

        def __init__(self, hass_instance):
            self.hass = hass_instance
            self._cache: dict[str, tuple] = {}  # entry_id -> (fetched_at, js_text, entitled)

        async def get(self, request):
            import time
            from .const import CONF_GRIDLENS_API_KEY, CONF_GRIDLENS_API_URL
            from .powerflow_locked import LOCKED_CARD_JS

            version = request.query.get("v", "")

            def _serve(js: str, entitled: bool) -> web.Response:
                text = js.replace("__CARD_VERSION__", version) if entitled else js
                return web.Response(text=text, content_type="application/javascript")

            entries = self.hass.config_entries.async_entries(DOMAIN)
            entry = entries[0] if entries else None
            if not entry:
                return _serve(LOCKED_CARD_JS, False)

            now = time.monotonic()
            cached = self._cache.get(entry.entry_id)
            if cached:
                fetched_at, js_text, entitled = cached
                ttl = self._TTL_ENTITLED if entitled else self._TTL_LOCKED
                if now - fetched_at < ttl:
                    return _serve(js_text, entitled)

            api_key = entry.data.get(CONF_GRIDLENS_API_KEY, "")
            api_url = entry.data.get(CONF_GRIDLENS_API_URL, "https://api.gridlens.au")
            try:
                session = async_get_clientsession(self.hass)
                async with session.get(
                    f"{api_url}/cards/powerflow",
                    headers={"X-API-Key": api_key, "User-Agent": "GridLens-HA-Integration/1.0"},
                    timeout=aiohttp.ClientTimeout(total=10),
                ) as resp:
                    if resp.status == 200:
                        js_raw = await resp.text()
                        self._cache[entry.entry_id] = (now, js_raw, True)
                        return _serve(js_raw, True)
                    if resp.status in (401, 402, 403):
                        self._cache[entry.entry_id] = (now, LOCKED_CARD_JS, False)
                        return _serve(LOCKED_CARD_JS, False)
                    _LOGGER.warning(
                        "Power Flow card: unexpected status %s from API", resp.status
                    )
            except Exception as err:  # noqa: BLE001 — network is best-effort here
                _LOGGER.warning("Power Flow card: could not reach API (%s)", err)

            # Network failure or an unexpected status: prefer stale-but-real over the
            # paywall — never punish a paying customer for an outage on our end.
            if cached and cached[2]:
                return _serve(cached[1], True)
            return _serve(LOCKED_CARD_JS, False)

    class PowerflowIconView(HomeAssistantView):
        """Proxies one of the Power Flow card's node icons from the API — same
        entitlement gate and server-to-server fetch pattern as PowerflowCardView
        above, just for a binary asset instead of JS. See that class's docstring
        for the browser-never-sees-the-API-key rationale, which applies here too.

        These icons moved here (from a static file under this integration's own
        www/icons/) 2026-08-05 — they'd been served publicly since before the
        card was gated, exclusively for this card's own use, undermining the
        exact protection this proxy exists to provide. See
        GRIDLENS_CHECKLIST.md's 2026-08-05 entry for the full story.

        Unlike the card JS, there's no "locked" placeholder image: if the
        install isn't entitled, the real diagram never renders in the first
        place (the paywall stub is a self-contained upsell UI with no node
        icons of its own), so nothing would ever request one of these URLs
        while un-entitled anyway. A 404 is a fine degradation for that case.
        """

        url = "/api/grid_lens/icons/{filename}"
        name = "api:grid_lens:powerflow_icon"
        requires_auth = False

        _TTL_ENTITLED = 3600  # icon bytes change far less often than card logic
        _TTL_LOCKED = 60      # still short, so an upgrade is reflected promptly

        def __init__(self, hass_instance):
            self.hass = hass_instance
            # (entry_id, filename) -> (fetched_at, content, content_type, entitled)
            self._cache: dict[tuple[str, str], tuple] = {}

        # The card JS appends a hand-bumped ?v= query string (ICON_V) to every icon
        # URL, changed whenever icon bytes change — so a given URL's content is
        # permanently fixed and safe to cache aggressively in the browser. Without
        # this, every request (including the query string) was refetched from HA on
        # every page load, since aiohttp's web.Response sends no cache headers by
        # default. That's most visible over the reverse-proxied FQDN path, where
        # these binary assets are also multiplexed as HTTP/2 streams over one
        # connection instead of the browser's parallel HTTP/1.1 connections used for
        # direct-IP access — repeated no-cache refetches compound that slowdown.
        _BROWSER_CACHE_HEADERS = {"Cache-Control": "public, max-age=31536000, immutable"}

        async def get(self, request, filename):
            import time
            from .const import CONF_GRIDLENS_API_KEY, CONF_GRIDLENS_API_URL

            entries = self.hass.config_entries.async_entries(DOMAIN)
            entry = entries[0] if entries else None
            if not entry:
                return web.Response(status=404)

            key = (entry.entry_id, filename)
            now = time.monotonic()
            cached = self._cache.get(key)
            if cached:
                fetched_at, content, content_type, entitled = cached
                ttl = self._TTL_ENTITLED if entitled else self._TTL_LOCKED
                if now - fetched_at < ttl:
                    return web.Response(
                        body=content, content_type=content_type,
                        headers=self._BROWSER_CACHE_HEADERS,
                    )

            api_key = entry.data.get(CONF_GRIDLENS_API_KEY, "")
            api_url = entry.data.get(CONF_GRIDLENS_API_URL, "https://api.gridlens.au")
            try:
                session = async_get_clientsession(self.hass)
                async with session.get(
                    f"{api_url}/cards/powerflow/icons/{filename}",
                    headers={"X-API-Key": api_key, "User-Agent": "GridLens-HA-Integration/1.0"},
                    timeout=aiohttp.ClientTimeout(total=10),
                ) as resp:
                    if resp.status == 200:
                        content = await resp.read()
                        content_type = resp.content_type
                        self._cache[key] = (now, content, content_type, True)
                        return web.Response(
                            body=content, content_type=content_type,
                            headers=self._BROWSER_CACHE_HEADERS,
                        )
                    if resp.status in (401, 402, 403, 404):
                        return web.Response(status=404)
                    _LOGGER.warning(
                        "Power Flow icon %s: unexpected status %s from API", filename, resp.status
                    )
            except Exception as err:  # noqa: BLE001 — network is best-effort here
                _LOGGER.warning("Power Flow icon %s: could not reach API (%s)", filename, err)

            # Network failure or an unexpected status: prefer stale-but-real over a
            # broken image, same principle as PowerflowCardView.
            if cached and cached[3]:
                return web.Response(
                    body=cached[1], content_type=cached[2],
                    headers=self._BROWSER_CACHE_HEADERS,
                )
            return web.Response(status=404)

