async def _ensure_load_estimators(hass: HomeAssistant, entry: ConfigEntry) -> tuple[dict, dict]:
    """Two related pieces of automatic LoadEstimator wiring, both run once here at the
    top of async_setup_entry (see the ordering note below):

    1. **"Estimated load" slots** (CONF_DEFERRABLE_LOAD_EST_*) — a device with a control
       entity but no energy sensor at all (e.g. an IR-blaster aircon). Splices a synthetic
       energy sensor into the normal sensor-backed CONF_DEFERRABLE_LOAD_SENSORS lists so
       the rest of the system treats it exactly like a device with a real meter.
    2. **Power-only inference** (added 2026-08-02, no config beyond CONF_LOAD_POWER_SENSOR
       needed) — for EVERY deferrable device with a control entity but no live
       power_entity resolvable by entity_lookup.resolve_power_sensor() — the common case
       for a device whose only telemetry is a cumulative energy counter (e.g. an ECHONET
       Lite aircon's measured_cumulative_power_consumption, device_class energy not
       power) — builds a power-only LoadEstimator (track_energy=False; the real
       accumulation already comes from the device's own sensor, this is ONLY for a live
       W reading) so the Power Flow card, which silently drops any node with no
       power_entity, can show it. Covers both sensor-backed devices AND the
       estimated-load ones from step 1. Silently does nothing (per device) if
       CONF_LOAD_POWER_SENSOR isn't configured — same fail-open discipline as every
       other optional sensor in this integration. Calibrates off the device's OWN
       cumulative energy sensor (energy_sensor=sensor_id — that sensor is the reason the
       device reached step 2 at all) rather than the whole-house load sensor whenever one
       is present, so a second concurrent load (e.g. another HVAC unit's compressor
       cycling, invisible as a discrete state change) can't contaminate the estimate —
       see load_estimation.py's module docstring.

    Returns (energy_estimators, power_estimators):
    - energy_estimators: {est_slot_index: LoadEstimator} — sensor.py wraps each in a
      GridLensEstimatedEnergySensor.
    - power_estimators: {sensor_id: LoadEstimator} — sensor.py wraps each in a
      GridLensEstimatedPowerSensor, and _build_deferrable_loads() falls back to it as
      the device's power_entity when resolve_power_sensor() finds nothing. An
      estimated-load slot's estimator appears in BOTH dicts (the same LoadEstimator
      instance — it has neither a real energy nor a real power sensor).

    Must run before anything else in async_setup_entry reads entry.data
    (GridLensCoordinator, LoadControlManager, PlanCalculator, AdvisoryCoordinator, and the
    platform entities all do) and before the config-entry update listener is registered —
    the async_update_entry call below (step 1 only) is a one-time, idempotent merge (a
    no-op once a slot's sensor id is already present in CONF_DEFERRABLE_LOAD_SENSORS), and
    with no listener registered yet it can't race a reload against this very setup call:
    the merged entry.data is simply already correct by the time everything else below
    reads it. See const.py's CONF_DEFERRABLE_LOAD_EST_* docstring for the design step 1
    implements.
    """
    from homeassistant.helpers import entity_registry as er
    from homeassistant.util import slugify

    from .const import (
        CONF_DEFERRABLE_LOAD_CL_IN_AGGREGATE,
        CONF_DEFERRABLE_LOAD_CLIMATE_ON_MODE,
        CONF_DEFERRABLE_LOAD_CONTROLLED_LOAD,
        CONF_DEFERRABLE_LOAD_EST_AUTO,
        CONF_DEFERRABLE_LOAD_EST_CONTROL,
        CONF_DEFERRABLE_LOAD_EST_KW,
        CONF_DEFERRABLE_LOAD_EST_NAMES,
        CONF_DEFERRABLE_LOAD_MAX_KW,
        CONF_DEFERRABLE_LOAD_SOC_SENSORS,
        CONF_DEFERRABLE_LOAD_SWITCHES,
        CONF_LOAD_POWER_SENSOR,
    )
    from .entity_lookup import resolve_device_name, resolve_power_sensor
    from .load_estimation import EstimateStore, LoadEstimator

    load_power_sensor = entry.data.get(CONF_LOAD_POWER_SENSOR) or ""
    ent_reg = er.async_get(hass)
    store = EstimateStore(hass, entry.entry_id)

    sensors = list(entry.data.get(CONF_DEFERRABLE_LOAD_SENSORS, []) or [])
    max_kw_list = list(entry.data.get(CONF_DEFERRABLE_LOAD_MAX_KW, []) or [])
    switches_list = list(entry.data.get(CONF_DEFERRABLE_LOAD_SWITCHES, []) or [])
    climate_mode_list = list(entry.data.get(CONF_DEFERRABLE_LOAD_CLIMATE_ON_MODE, []) or [])
    soc_list = list(entry.data.get(CONF_DEFERRABLE_LOAD_SOC_SENSORS, []) or [])
    cl_list = list(entry.data.get(CONF_DEFERRABLE_LOAD_CONTROLLED_LOAD, []) or [])
    in_agg_list = list(entry.data.get(CONF_DEFERRABLE_LOAD_CL_IN_AGGREGATE, []) or [])
    # Every parallel list must stay the same length as `sensors` — relied on throughout
    # plan_calculator.py/LoadControlManager (index i always means "device i").
    _pairs = (
        (max_kw_list, 3.5), (switches_list, ""), (climate_mode_list, ""),
        (soc_list, ""), (cl_list, ""), (in_agg_list, False),
    )
    for lst, fill in _pairs:
        lst.extend([fill] * (len(sensors) - len(lst)))

    # ------------------------------------------------------------ step 1: estimated loads
    names = list(entry.data.get(CONF_DEFERRABLE_LOAD_EST_NAMES, []) or [])
    controls = list(entry.data.get(CONF_DEFERRABLE_LOAD_EST_CONTROL, []) or [])
    kws = list(entry.data.get(CONF_DEFERRABLE_LOAD_EST_KW, []) or [])
    autos = list(entry.data.get(CONF_DEFERRABLE_LOAD_EST_AUTO, []) or [])
    # Every control entity already known BEFORE constructing any estimator, so slot 0's
    # "others" list correctly includes slot 1/2's control entities even though they're
    # constructed later in the loop below.
    all_control_entities = [c for c in controls if c] + [s for s in switches_list if s]

    energy_estimators: dict[int, LoadEstimator] = {}
    power_estimators: dict[str, LoadEstimator] = {}
    changed = False
    for i, raw_name in enumerate(names):
        name = str(raw_name).strip()
        if not name:
            continue
        control = str(controls[i]).strip() if i < len(controls) else ""
        if not control:
            _LOGGER.warning(
                "Estimated deferrable load %r has no control entity configured — skipping",
                name,
            )
            continue
        seed_kw = float(kws[i]) if i < len(kws) and kws[i] not in (None, "") else 1.0
        auto = bool(autos[i]) if i < len(autos) else False

        unique_id = f"{entry.entry_id}_est_{i}"
        reg_entry = ent_reg.async_get_or_create(
            "sensor", DOMAIN, unique_id,
            suggested_object_id=f"{slugify(name)}_estimated_consumption",
            config_entry=entry,
        )
        sensor_id = reg_entry.entity_id
        power_reg_entry = ent_reg.async_get_or_create(
            "sensor", DOMAIN, f"{unique_id}_power",
            suggested_object_id=f"{slugify(name)}_estimated_power",
            config_entry=entry,
        )

        others = [e for e in all_control_entities if e != control]
        estimator = LoadEstimator(
            hass, store=store, store_key=unique_id, name=name,
            control_entity_id=control, seed_kw=seed_kw, auto_refine=auto,
            load_power_sensor=load_power_sensor, other_control_entity_ids=others,
        )
        # Metadata only (never read internally by LoadEstimator) — the power sensor
        # entity sensor.py should wrap around this same estimator. See the class
        # docstring's "power_sensor_entity_id" note.
        estimator.power_unique_id = f"{unique_id}_power"
        estimator.power_sensor_entity_id = power_reg_entry.entity_id
        energy_estimators[i] = estimator
        power_estimators[sensor_id] = estimator

        if sensor_id not in sensors:
            sensors.append(sensor_id)
            max_kw_list.append(seed_kw)
            switches_list.append(control)
            climate_mode_list.append("")
            soc_list.append("")
            cl_list.append("")
            in_agg_list.append(False)
            changed = True

    if changed:
        hass.config_entries.async_update_entry(entry, data={
            **entry.data,
            CONF_DEFERRABLE_LOAD_SENSORS: sensors,
            CONF_DEFERRABLE_LOAD_MAX_KW: max_kw_list,
            CONF_DEFERRABLE_LOAD_SWITCHES: switches_list,
            CONF_DEFERRABLE_LOAD_CLIMATE_ON_MODE: climate_mode_list,
            CONF_DEFERRABLE_LOAD_SOC_SENSORS: soc_list,
            CONF_DEFERRABLE_LOAD_CONTROLLED_LOAD: cl_list,
            CONF_DEFERRABLE_LOAD_CL_IN_AGGREGATE: in_agg_list,
        })

    # ------------------------------------------------------- step 2: power-only inference
    # `switches_list` is now final (real devices + any estimated-load ones just spliced
    # in above), so this "others" set covers the whole household.
    if load_power_sensor:
        all_control_entities_final = [s for s in switches_list if s]
        for i, sensor_id in enumerate(sensors):
            if sensor_id in power_estimators:
                continue  # an estimated-load device — already covered in step 1
            control = switches_list[i] if i < len(switches_list) else ""
            if not control:
                continue  # forecast-only device, nothing to actuate/watch transitions on
            try:
                existing_power = resolve_power_sensor(hass, sensor_id, control)
            except Exception:  # noqa: BLE001 — discovery is best-effort
                existing_power = None
            if existing_power:
                continue  # already has real live power telemetry — nothing to estimate
            name = resolve_device_name(hass, control, sensor_id) or sensor_id
            seed_kw = float(max_kw_list[i]) if i < len(max_kw_list) else 1.0
            unique_id = f"{entry.entry_id}_pwr_{i}"
            reg_entry = ent_reg.async_get_or_create(
                "sensor", DOMAIN, unique_id,
                suggested_object_id=f"{slugify(name)}_estimated_power",
                config_entry=entry,
            )
            others = [e for e in all_control_entities_final if e != control]
            estimator = LoadEstimator(
                hass, store=store, store_key=unique_id, name=name,
                control_entity_id=control, seed_kw=seed_kw, auto_refine=True,
                load_power_sensor=load_power_sensor, other_control_entity_ids=others,
                track_energy=False,
                # sensor_id is by construction a cumulative energy sensor here (the whole
                # reason this device reached step 2 is that it has no live power_entity) —
                # calibrate the live-W estimate off the device's own meter rather than the
                # whole-house load sensor, so a second concurrent load (e.g. another HVAC
                # unit) can't contaminate it. See load_estimation.py's module docstring.
                energy_sensor=sensor_id,
            )
            estimator.power_unique_id = unique_id
            estimator.power_sensor_entity_id = reg_entry.entity_id
            power_estimators[sensor_id] = estimator

    # An estimated-load estimator is referenced from both dicts (same instance) —
    # load/start each unique estimator exactly once.
    unique_estimators: list[LoadEstimator] = []
    seen = set()
    for estimator in [*energy_estimators.values(), *power_estimators.values()]:
        if id(estimator) not in seen:
            seen.add(id(estimator))
            unique_estimators.append(estimator)
    for estimator in unique_estimators:
        await estimator.async_load()
        estimator.start()

    return energy_estimators, power_estimators


async def _notify_unpainted_climate_schedules(hass: HomeAssistant, entry: ConfigEntry, sched_store) -> None:
    """Nudge for a climate.*-controlled deferrable load (aircon) with no painted weekly
    schedule (§8 in FEATURES.md).

    A device with no stored grid is fully unrestricted — any hour — which is a reasonable
    default for a pool pump or EV charger (their daily energy genuinely can land anywhere),
    but not for an air conditioner: comfort, not price, decides when it needs to run, so an
    unpainted aircon lets the optimiser assume it can shift a whole day's runtime to 3am in
    both plan comparison and the real dispatch/control plan (same LP, FEATURES.md §0/§2).
    Runs once per setup/reload; re-evaluates every time so the notification clears itself
    once every climate.*-backed device has a schedule painted.
    """
    from .const import CONF_DEFERRABLE_LOAD_SENSORS, CONF_DEFERRABLE_LOAD_SWITCHES
    from .entity_lookup import resolve_device_name

    sensors = list(entry.data.get(CONF_DEFERRABLE_LOAD_SENSORS, []) or [])
    switches = list(entry.data.get(CONF_DEFERRABLE_LOAD_SWITCHES, []) or [])
    notification_id = f"grid_lens_unpainted_climate_schedule_{entry.entry_id}"

    unpainted = []
    for i, sensor_id in enumerate(sensors):
        control = switches[i] if i < len(switches) else ""
        if not control.startswith("climate."):
            continue
        if await sched_store.async_get(sensor_id) is not None:
            continue  # already painted
        unpainted.append(resolve_device_name(hass, control, sensor_id) or control)

    if not unpainted:
        persistent_notification.async_dismiss(hass, notification_id)
        return

    device_list = "\n".join(f"- {name}" for name in unpainted)
    persistent_notification.async_create(
        hass,
        "A deferrable load with no painted schedule is treated as reschedulable to **any "
        "hour** — reasonable for a pool pump or EV charger, but usually wrong for an air "
        "conditioner, since you run it for real-time comfort, not to chase the cheapest "
        "hour. Without a schedule, plan comparisons and the dispatch plan may assume it "
        f"could run at 3am.\n\nPaint allowed run times for:\n{device_list}\n\non the "
        "**Deferrable Loads** dashboard card's weekly schedule.",
        title="Grid Lens: Set aircon run-time hours",
        notification_id=notification_id,
    )


async def async_setup_entry(hass: HomeAssistant, entry: ConfigEntry) -> bool:
    """Set up Grid Lens from a config entry."""
    _LOGGER.info("Setting up Grid Lens")

    hass.data.setdefault(DOMAIN, {})

    # Must run first, before anything below reads entry.data and before the update
    # listener is registered (see _ensure_load_estimators's own docstring for why).
    _energy_estimators, _power_estimators = await _ensure_load_estimators(hass, entry)
    hass.data[DOMAIN][f"{entry.entry_id}_load_estimators"] = _energy_estimators
    hass.data[DOMAIN][f"{entry.entry_id}_power_estimators"] = _power_estimators

    coordinator = GridLensCoordinator(hass, entry)
    hass.data[DOMAIN][entry.entry_id] = coordinator
    entry.async_on_unload(entry.add_update_listener(_async_update_listener))

    # Per-day deferrable load overrides (Feature 2) — independent of battery/control,
    # shared between the number.py entities and AdvisoryCoordinator. Created before the
    # platforms are forwarded so number.py can look it up during its own setup.
    from .deferrable_overrides import DeferrableOverrideStore
    hass.data[DOMAIN][f"{entry.entry_id}_deferrable_overrides"] = DeferrableOverrideStore(
        hass, entry.entry_id
    )

    # Weekly per-weekday availability schedules for deferrable loads (edited on the
    # dashboard schedule card; replaces the static hours config when set for a device).
    # Preloaded here so sensor.py's sync attribute builder can read the cache.
    from .deferrable_schedules import DeferrableScheduleStore
    _sched_store = DeferrableScheduleStore(hass, entry.entry_id)
    await _sched_store.async_load()
    hass.data[DOMAIN][f"{entry.entry_id}_deferrable_schedules"] = _sched_store

    await _notify_unpainted_climate_schedules(hass, entry, _sched_store)

    # GridLens-owned daily energy archive: captures per-day PV/import/export totals
    # into HA Storage so long-horizon features never depend on the user's recorder
    # retention (backfills from long-term statistics, then appends nightly).
    try:
        from homeassistant.helpers.event import async_track_time_change

        from .daily_archive import DailyEnergyArchive
        _archive = DailyEnergyArchive(hass, entry)
        hass.data[DOMAIN][f"{entry.entry_id}_daily_archive"] = _archive
        entry.async_create_background_task(
            hass, _archive.async_backfill(), name="grid_lens_daily_archive_backfill"
        )
        # 00:20 local: late enough that the recorder has compiled yesterday's last
        # daily-statistics bucket, early enough to be ready for morning planning.
        entry.async_on_unload(
            async_track_time_change(
                hass,
                lambda now: entry.async_create_background_task(
                    hass, _archive.async_daily_tick(now), name="grid_lens_daily_archive_tick"
                ),
                hour=0,
                minute=20,
                second=0,
            )
        )
    except Exception as _arch_err:  # noqa: BLE001
        _LOGGER.warning("Daily energy archive setup failed: %s", _arch_err)

    # Advisory mode (forecast-fed planning, read-only). Independent coordinator so it
    # never disturbs the manual plan-comparison flow. Best-effort — failures don't block.
    try:
        from .advisory.coordinator import AdvisoryCoordinator
        _adv = AdvisoryCoordinator(hass, entry)
        # Seed the last persisted plan BEFORE the sensor platform is set up, so the card
        # renders the previous plan instantly on restart instead of sitting blank until
        # live SOC/forecast arrive (Sigen Modbus SOC can take minutes to appear).
        await _adv.async_load_cached()
        hass.data[DOMAIN][f"{entry.entry_id}_advisory"] = _adv
    except Exception as _adv_err:  # noqa: BLE001
        _LOGGER.warning("Advisory mode setup failed: %s", _adv_err)

    # Battery control manager (actuation). Created but INERT until the master switch is
    # turned on — no charge/discharge writes on setup (the one exception is pushing the
    # hardware safety floor below, which is a passive bound, not an actuation). Deadman
    # restores native EMS on disable/stop.
    if entry.data.get("has_battery", False):
        try:
            from .control.manager import ControlManager
            _ctl_mgr = ControlManager(hass, entry)
            hass.data[DOMAIN][f"{entry.entry_id}_control"] = _ctl_mgr
            # Restore user intent (persisted independently of the switch entity's own
            # restore-state — see ControlManager.async_initialize()'s docstring) before
            # the switch platform is forwarded, so its initial displayed state is
            # already correct rather than defaulting off and flipping on moments later.
            await _ctl_mgr.async_initialize()
            # Push the hardware discharge floor now rather than waiting for the first
            # force_discharge() call — closes the window where a restart leaves the
            # floor software-only. Best-effort: if the inverter's entity surface isn't
            # up yet, the advisory coordinator's periodic tick retries this until it
            # lands (see AdvisoryCoordinator._refresh_meta).
            await _ctl_mgr.async_push_safety_floor()
        except Exception as _ctl_err:  # noqa: BLE001
            _LOGGER.warning("Battery control setup failed: %s", _ctl_err)

    # Deferrable-load control manager (actuation for on/off AND modulating loads). Independent
    # of has_battery — created whenever any deferrable device has a control entity configured,
    # which since the modulating-load feature means a control switch OR a current/power
    # setpoint. has_controllable() is the single test for that: the manager builds one
    # controller per device of either type into the same dict, so no separate setpoint check
    # is needed here. INERT until its per-device master switch is turned on (default OFF); no
    # switch or setpoint writes on setup. Deadman = leave loads as-is (never forces off).
    try:
        from .control.load_control_manager import LoadControlManager
        _load_mgr = LoadControlManager(hass, entry)
        if _load_mgr.has_controllable():
            hass.data[DOMAIN][f"{entry.entry_id}_load_control"] = _load_mgr
    except Exception as _load_err:  # noqa: BLE001
        _LOGGER.warning("Deferrable load control setup failed: %s", _load_err)

    # Register services
    from .services import async_setup_services
    await async_setup_services(hass, entry)

    await hass.config_entries.async_forward_entry_setups(entry, PLATFORMS)

    # Pre-calculate in the background so the card has data immediately on load. The
    # advisory refresh is chained AFTER the main one (awaited), because it reads the
    # main coordinator's plan_data — running them concurrently races and leaves the
    # advisory sensor stuck "waiting" until its next 10-min tick.
    async def _startup_refresh():
        await coordinator.async_refresh()
        _advisory = hass.data[DOMAIN].get(f"{entry.entry_id}_advisory")
        if _advisory is not None:
            await _advisory.async_refresh()

    hass.async_create_task(_startup_refresh())

    return True


async def async_unload_entry(hass: HomeAssistant, entry: ConfigEntry) -> bool:
    """Unload a config entry."""
    # Deadman: if battery control is active, restore native EMS before tearing down.
    # Uses async_prepare_for_reload(), NOT disable() — this fires on every reload
    # regardless of user intent, so it must not clear the persisted "want enabled"
    # flag (see ControlManager.async_initialize()'s docstring for the incident that
    # caused when this used disable()).
    _mgr = hass.data.get(DOMAIN, {}).get(f"{entry.entry_id}_control")
    if _mgr is not None:
        try:
            await _mgr.async_prepare_for_reload()
        except Exception:  # noqa: BLE001
            pass

    # Load control deadman = leave loads as-is: stop ticking, never force a switch off.
    _load_mgr = hass.data.get(DOMAIN, {}).get(f"{entry.entry_id}_load_control")
    if _load_mgr is not None:
        try:
            _load_mgr.shutdown()
        except Exception:  # noqa: BLE001
            pass

    # Stop each estimator's listeners/timers — nothing to actuate on teardown, this is
    # just cancelling background work (unlike battery/load control, no deadman needed).
    # An estimated-load estimator lives in both dicts (same instance) — stop each unique
    # one exactly once.
    _energy_ests = hass.data.get(DOMAIN, {}).get(f"{entry.entry_id}_load_estimators", {})
    _power_ests = hass.data.get(DOMAIN, {}).get(f"{entry.entry_id}_power_estimators", {})
    _seen_est_ids: set = set()
    for _est in [*_energy_ests.values(), *_power_ests.values()]:
        if id(_est) in _seen_est_ids:
            continue
        _seen_est_ids.add(id(_est))
        try:
            _est.stop()
        except Exception:  # noqa: BLE001
            pass

    if unload_ok := await hass.config_entries.async_unload_platforms(entry, PLATFORMS):
        hass.data[DOMAIN].pop(entry.entry_id)
        hass.data[DOMAIN].pop(f"{entry.entry_id}_advisory", None)
        hass.data[DOMAIN].pop(f"{entry.entry_id}_control", None)
        hass.data[DOMAIN].pop(f"{entry.entry_id}_load_control", None)
        hass.data[DOMAIN].pop(f"{entry.entry_id}_deferrable_overrides", None)
        hass.data[DOMAIN].pop(f"{entry.entry_id}_deferrable_schedules", None)
        hass.data[DOMAIN].pop(f"{entry.entry_id}_load_estimators", None)
        hass.data[DOMAIN].pop(f"{entry.entry_id}_power_estimators", None)

    return unload_ok


class GridLensCoordinator(DataUpdateCoordinator):
    """Coordinator to manage electricity plan comparison data."""

    def __init__(self, hass: HomeAssistant, entry: ConfigEntry) -> None:
        """Initialize coordinator."""
        super().__init__(
            hass,
            _LOGGER,
            name=DOMAIN,
            update_interval=None,  # Manual refresh only — never auto-calculate
        )
        self.entry = entry
        self.hass = hass
        self.calculator = None  # Will be created on first update
        self.energy_dashboard_names: dict[str, str] = {}

    async def _async_update_data(self):
        """Fetch data from energy sensors and calculate plan comparisons."""
        import aiohttp
        from .plan_calculator import PlanCalculator
        from .const import CONF_GRIDLENS_API_KEY, CONF_GRIDLENS_API_URL, CONF_STATE
        from .entity_lookup import async_get_energy_dashboard_names

        self.energy_dashboard_names = await async_get_energy_dashboard_names(self.hass)

        api_key = self.entry.data.get(CONF_GRIDLENS_API_KEY, "")
        api_url = self.entry.data.get(CONF_GRIDLENS_API_URL, "https://api.gridlens.au")
        state   = self.entry.data.get(CONF_STATE, "NSW")
        network = self.entry.data.get(CONF_DISTRIBUTOR, "")

        plan_data: dict = {}
        network_operators: dict = {}
        try:
            import aiohttp as _aiohttp
            _session = async_get_clientsession(self.hass)
            async with _session.get(
                f"{api_url}/plans",
                params={"state": state, "current_plan": self.entry.data.get("current_plan", ""), "network": network},
                headers={"X-API-Key": api_key, "User-Agent": "GridLens-HA-Integration/1.0"},
                timeout=_aiohttp.ClientTimeout(total=15),
            ) as _r:
                if _r.status == 200:
                    _resp = await _r.json()
                    plan_data = _resp.get("plans", {})
                    network_operators = _resp.get("network_operators", {})
                elif _r.status == 402:
                    _LOGGER.warning("Coordinator: API /plans returned 402 (subscription ended)")
                    persistent_notification.async_create(
                        self.hass,
                        "Your Grid Lens subscription has ended and the dashboard cannot show plan data. "
                        "Please resubscribe at **gridlens.au/pricing** or reconfigure the integration "
                        "to restore your original plan.",
                        title="Grid Lens: Subscription Ended",
                        notification_id="grid_lens_subscription_ended",
                    )
                else:
                    _LOGGER.warning("Coordinator: API /plans returned %s", _r.status)
        except Exception as _exc:
            _LOGGER.warning("Coordinator: could not fetch plan data: %s", _exc)

        self.calculator = PlanCalculator(self.hass, self.entry)
        self.calculator.plan_data = plan_data
        self.calculator.network_operators = network_operators
        result = await self.calculator.calculate_plan_costs()
        _LOGGER.info(f"Plan calculation complete: {result.get('usage_days', 0)} days")

        # Build per-plan sensor data for CoordinatorEntity sensors
        plan_metrics = {}
        plan_details = result.get("plan_details", {})
        for plan_id, plan_key in PLAN_ID_TO_KEY.items():
            detail = plan_details.get(plan_key, {})
            opt = detail.get("optimization", {})
            schedule = opt.get("schedule", [])

            total_import = opt.get("total_import_kwh", 0.0) or 0.0
            total_export = opt.get("total_export_kwh", 0.0) or 0.0
            total_import_cost = opt.get("total_import_cost", 0.0) or 0.0
            total_export_credit = opt.get("total_export_credit", 0.0) or 0.0
            total_charge = sum(h.get("charge_kwh", 0) for h in schedule)
            total_discharge = sum(h.get("discharge_kwh", 0) for h in schedule)
            net_cost = opt.get("net_cost", detail.get("breakdown", {}).get("total", 0.0)) or 0.0

            plan_metrics[plan_id] = {
                "grid_import": round(total_import, 3),
                "grid_export": round(total_export, 3),
                "battery_charge": round(total_charge, 3),
                "battery_discharge": round(total_discharge, 3),
                "solar_production": 0.0,
                "buy_price": round(total_import_cost / total_import, 4) if total_import else 0.0,
                "sell_price": round(total_export_credit / total_export, 4) if total_export else 0.0,
                "hourly_cost": round(net_cost / len(schedule), 4) if schedule else 0.0,
                "optimization_notes": detail.get("strategy", ""),
            }

        result["plan_metrics"] = plan_metrics
        return result
